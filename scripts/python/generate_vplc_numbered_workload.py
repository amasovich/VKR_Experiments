#!/usr/bin/env python3
"""Generate a VPLC ST fallback workload without ARRAY syntax."""

from __future__ import annotations

from pathlib import Path


HEADER = """(* VKR VPLC workload v0.2 fallback.
   Numbered-state variant for VPLC Studio if ARRAY variables are not accepted.
   Generated by scripts/python/generate_vplc_numbered_workload.py.
*)

IF NOT init_done THEN
    load_level := 0;
    T0_ms := 10.0;
    deadline_threshold_ms := 20.0;
    load_passes_level1 := 32;
    load_passes_level2 := 128;
    load_passes_level3 := 512;
    max_load_passes := 512;
    heartbeat_divisor_cycles := 100;
    accumulator_modulus := 2147483647;
    init_done := TRUE;
END_IF;

divisor_two := 2;

cycle_counter := cycle_counter + 1;

heartbeat_divider := heartbeat_divider + 1;
IF heartbeat_divider >= heartbeat_divisor_cycles THEN
    heartbeat := NOT heartbeat;
    heartbeat_divider := 0;
END_IF;

load_passes := 0;

IF load_level = 0 THEN
    error_flag := FALSE;
    effective_load_level := 0;
ELSIF load_level = 1 THEN
    error_flag := FALSE;
    effective_load_level := 1;
    load_passes := load_passes_level1;
ELSIF load_level = 2 THEN
    error_flag := FALSE;
    effective_load_level := 2;
    load_passes := load_passes_level2;
ELSIF load_level = 3 THEN
    error_flag := FALSE;
    effective_load_level := 3;
    load_passes := load_passes_level3;
ELSE
    error_flag := TRUE;
    effective_load_level := 0;
    load_passes := 0;
END_IF;

IF load_passes > max_load_passes THEN
    load_passes := max_load_passes;
END_IF;

load_level_effective := effective_load_level;
load_passes_effective := load_passes;

workload_accumulator := workload_accumulator + cycle_counter + effective_load_level;
DIVMOD(workload_accumulator, accumulator_modulus, tmp_quotient, tmp_modulo);
workload_accumulator := tmp_modulo;

IF load_passes > 0 THEN
    FOR p := 1 TO load_passes DO
"""

FOOTER = """    END_FOR;
END_IF;
"""


def state_block(index: int) -> str:
    return f"""        int_state_{index} := int_state_{index} + cycle_counter + {index} + p + effective_load_level;
        DIVMOD(int_state_{index}, accumulator_modulus, tmp_quotient, tmp_modulo);
        int_state_{index} := tmp_modulo;
        DIVMOD(int_state_{index}, divisor_two, tmp_quotient, tmp_modulo);
        bool_state_{index} := tmp_modulo = 0;
        IF bool_state_{index} THEN
            workload_accumulator := workload_accumulator + int_state_{index};
            DIVMOD(workload_accumulator, accumulator_modulus, tmp_quotient, tmp_modulo);
            workload_accumulator := tmp_modulo;
        ELSE
            workload_accumulator := workload_accumulator + {index} + p;
            DIVMOD(workload_accumulator, accumulator_modulus, tmp_quotient, tmp_modulo);
            workload_accumulator := tmp_modulo;
        END_IF;

"""


def main() -> int:
    out = Path("vplc/masc_vplc/st_sources/VPLC_WorkloadCycle_v0_2_numbered.st")
    out.parent.mkdir(parents=True, exist_ok=True)
    body = HEADER + "".join(state_block(i) for i in range(16)) + FOOTER
    out.write_text(body, encoding="utf-8")
    print(out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
